"""Move static inline style="" attributes in templates into utility classes in v3.css.
Dynamic styles (containing {{ }}) stay inline: they carry per-item values (meter widths, map pins).
python3 scripts/inline_to_classes.py   (idempotent)
"""
import re, pathlib
ROOT = pathlib.Path(__file__).resolve().parents[1]
FILES = [p for p in (ROOT / "src").rglob("*.njk")]
CSS = ROOT / "src/assets/css/v3.css"
MARK = "/* ---------- Utilities (moved from inline styles; generated by scripts/inline_to_classes.py) ---------- */"

SHORT = {"margin": "m", "margin-top": "mt", "margin-bottom": "mb", "padding": "p", "padding-bottom": "pb",
         "font-size": "fs", "font-weight": "fw", "color": "c", "max-width": "maxw", "min-width": "minw",
         "height": "h", "gap": "gap", "line-height": "lh", "text-align": "ta", "align-self": "self",
         "list-style": "list", "flex": "flex", "display": "d", "justify-content": "jc", "border-top": "bt"}

def cls_for(decl):
    prop, val = [x.strip() for x in decl.split(":", 1)]
    v = val.replace("var(--", "").replace(")", "").replace("px", "").replace("flex-start", "start").replace("space-between", "between")
    v = re.sub(r"[^a-z0-9.]+", "-", v.lower()).strip("-").replace(".", "_")
    return f"{SHORT.get(prop, prop)}-{v}", f"{prop}:{val}"

rules = {}
tag_re = re.compile(r"<([a-zA-Z][\w-]*)([^<>]*?)\sstyle=\"([^\"{}]*)\"([^<>]*?)(/?)>")
changed = 0
for f in FILES:
    s = f.read_text(encoding="utf-8")
    def repl(m):
        global changed
        name, pre, style, post, slash = m.groups()
        names = []
        for d in [d for d in style.split(";") if d.strip()]:
            c, rule = cls_for(d); rules[c] = rule; names.append(c)
        attrs = pre + post
        cm = re.search(r'\sclass="([^"]*)"', attrs)
        if cm:
            attrs = attrs.replace(cm.group(0), f' class="{cm.group(1)} {" ".join(names)}"', 1)
        else:
            attrs = f' class="{" ".join(names)}"' + attrs
        changed += 1
        return f"<{name}{attrs}{slash}>"
    new = tag_re.sub(repl, s)
    if new != s: f.write_text(new, encoding="utf-8")

css = CSS.read_text(encoding="utf-8")
if MARK in css:
    head, _, tail = css.partition(MARK)
    old = dict(re.findall(r"\.([\w-]+) \{ ([^}]*?) !important; \}", tail))
    for k, v in old.items(): rules.setdefault(k, v.replace(": ", ":", 1))
    css = head.rstrip() + "\n"
block = "\n" + MARK + "\n" + "\n".join(f".{k} {{ {v.split(':',1)[0]}: {v.split(':',1)[1]} !important; }}" for k, v in sorted(rules.items())) + "\n"
CSS.write_text(css + block, encoding="utf-8")
print(f"moved {changed} inline styles into {len(rules)} utility classes")
