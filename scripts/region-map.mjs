// Writes src/_data/regionGrid.json: the land grid for the homepage pixel map.
// Land and country shapes: Natural Earth 1:110m via the world-atlas package (public domain).
// Each row is a string, one character per cell: "." sea, "0" land, CODES[n] = the n-th region in
// home.yml → regions that has a slug and an iso code ("1".."9", then "a"). iso is one ISO 3166 numeric
// code or a list of them (the EU is one region of 27 countries). Run after adding a region ranking:
//   node scripts/region-map.mjs
import fs from "node:fs";
import yaml from "js-yaml";
import { feature } from "topojson-client";
import { geoContains } from "d3-geo";

const root = new URL("../", import.meta.url);
const topo = JSON.parse(fs.readFileSync(new URL("node_modules/world-atlas/countries-110m.json", root)));
const land = feature(topo, topo.objects.land);
const countries = feature(topo, topo.objects.countries).features;
const home = yaml.load(fs.readFileSync(new URL("src/_data/home.yml", root), "utf8"));
const CODES = "123456789a";   // at most 10 lit regions (owner, 2026-11-23)
const lit = home.regions.filter((r) => r.slug && r.iso);
if (lit.length > CODES.length) throw new Error(`region-map: at most ${CODES.length} lit regions`);
const shapes = lit.map((r) => {
  const isos = [].concat(r.iso).map(String);
  const found = countries.filter((c) => isos.includes(c.id));
  if (!found.length) throw new Error(`region-map: no country with iso ${isos.join(", ")} (${r.name})`);
  const missing = isos.filter((x) => !found.some((c) => c.id === x));
  if (missing.length) console.log(`region-map: ${r.name}: not in the 1:110m map (too small): ${missing.join(", ")}`);
  return found;
});

const step = 1.8, top = 82, bottom = -58;
const cols = Math.round(360 / step), rows = Math.round((top - bottom) / step), grid = [];
for (let r = 0; r < rows; r++) {
  let row = "";
  for (let c = 0; c < cols; c++) {
    const pt = [-180 + (c + 0.5) * step, top - (r + 0.5) * step];
    if (!geoContains(land, pt)) { row += "."; continue; }
    const i = shapes.findIndex((s) => s.some((f) => geoContains(f, pt)));
    row += i < 0 ? "0" : CODES[i];
  }
  grid.push(row);
}
const out = { note: "Generated by scripts/region-map.mjs from Natural Earth 1:110m (world-atlas). Do not edit.",
  step, top, bottom, cols, rows, codes: CODES, regions: lit.map((r) => r.slug), grid };
fs.writeFileSync(new URL("src/_data/regionGrid.json", root), JSON.stringify(out) + "\n");
console.log(`region-map: ${cols}x${rows} cells, ${lit.length} lit regions`);
